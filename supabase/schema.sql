-- Savor & Co. schema for Supabase (PostgreSQL)
-- Run this entire file in Supabase → SQL Editor → New query.
create extension if not exists pgcrypto;

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text not null default '',
  category text not null default 'Popular',
  price numeric(10,2) not null check (price >= 0),
  image_url text not null default '',
  available boolean not null default true,
  featured boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.store_settings (
  id integer primary key default 1 check (id=1),
  store_name text not null default 'Savor & Co.',
  tagline text not null default 'Good food. Good mood.',
  owner_email text not null default '',
  phone text not null default '',
  address text not null default '',
  delivery_fee numeric(10,2) not null default 150 check(delivery_fee>=0),
  currency text not null default 'PKR',
  updated_at timestamptz not null default now()
);
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_phone text not null,
  customer_email text not null default '',
  delivery_address text not null,
  delivery_notes text not null default '',
  subtotal numeric(10,2) not null,
  delivery_fee numeric(10,2) not null default 0,
  total numeric(10,2) not null,
  status text not null default 'new' check(status in ('new','confirmed','preparing','out_for_delivery','completed','cancelled')),
  payment_method text not null default 'cash_on_delivery',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid,
  product_name text not null,
  unit_price numeric(10,2) not null,
  quantity integer not null check(quantity between 1 and 20),
  line_total numeric(10,2) not null
);

-- Owner allow-list. Create the owner's Supabase Auth account first, then insert its UUID here.
create table if not exists public.store_owners (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create or replace function public.is_store_owner()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.store_owners where user_id=auth.uid()); $$;
revoke all on function public.is_store_owner() from public;
grant execute on function public.is_store_owner() to authenticated;

alter table public.products enable row level security;
alter table public.store_settings enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.store_owners enable row level security;

drop policy if exists "Public can view available products" on public.products;
create policy "Public can view available products" on public.products for select to anon, authenticated using (available=true or public.is_store_owner());
drop policy if exists "Owners manage products" on public.products;
create policy "Owners manage products" on public.products for all to authenticated using(public.is_store_owner()) with check(public.is_store_owner());

