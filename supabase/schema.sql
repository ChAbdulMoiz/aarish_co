create policy "Public can view store settings" on public.store_settings for select to anon, authenticated using(true);
drop policy if exists "Owners update store settings" on public.store_settings;
create policy "Owners update store settings" on public.store_settings for all to authenticated using(public.is_store_owner()) with check(public.is_store_owner());

