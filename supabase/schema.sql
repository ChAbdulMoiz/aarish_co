-- Checkout RPC: validates current prices/availability and creates order + lines atomically.
create or replace function public.place_order(
  p_customer_name text, p_customer_phone text, p_customer_email text default '',
  p_delivery_address text default '', p_delivery_notes text default '', p_items jsonb default '[]'::jsonb
) returns jsonb language plpgsql security definer set search_path=public
as $$
declare
  v_order public.orders%rowtype;
  v_subtotal numeric(10,2):=0;
  v_fee numeric(10,2):=150;
  v_item jsonb;
  v_pid uuid;
  v_qty integer;
  v_product public.products%rowtype;
  v_count integer:=0;
begin
  if length(trim(coalesce(p_customer_name,''))) not between 1 and 100
     or length(trim(coalesce(p_customer_phone,''))) not between 1 and 40
     or length(trim(coalesce(p_delivery_address,''))) not between 1 and 500 then
    raise exception 'Please provide your name, phone number and delivery address.';
  end if;
  if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 or jsonb_array_length(p_items)>30 then
    raise exception 'Your cart is empty or contains too many different items.';
  end if;
  select delivery_fee into v_fee from public.store_settings where id=1;
  v_fee:=coalesce(v_fee,150);
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_pid:=(v_item->>'product_id')::uuid;
    v_qty:=(v_item->>'quantity')::integer;
    if v_qty<1 or v_qty>20 then raise exception 'Each quantity must be between 1 and 20.'; end if;
    select * into v_product from public.products where id=v_pid and available=true;
    if not found then raise exception 'A product is no longer available. Please refresh your cart.'; end if;
    v_subtotal:=v_subtotal+(v_product.price*v_qty);
    v_count:=v_count+v_qty;
  end loop;
  if v_count>100 then raise exception 'Your order contains too many items.'; end if;
  insert into public.orders(customer_name,customer_phone,customer_email,delivery_address,delivery_notes,subtotal,delivery_fee,total)
  values(trim(p_customer_name),trim(p_customer_phone),left(coalesce(p_customer_email,''),160),trim(p_delivery_address),left(coalesce(p_delivery_notes,''),500),v_subtotal,v_fee,v_subtotal+v_fee)
  returning * into v_order;
  for v_item in select value from jsonb_array_elements(p_items) loop
    v_pid:=(v_item->>'product_id')::uuid; v_qty:=(v_item->>'quantity')::integer;
    select * into v_product from public.products where id=v_pid and available=true;
    insert into public.order_items(order_id,product_id,product_name,unit_price,quantity,line_total)
    values(v_order.id,v_product.id,v_product.name,v_product.price,v_qty,v_product.price*v_qty);
  end loop;
  return jsonb_build_object('id',v_order.id,'order_number',v_order.order_number,'status',v_order.status,'total',v_order.total);
end; $$;
revoke all on function public.place_order(text,text,text,text,text,jsonb) from public;
grant execute on function public.place_order(text,text,text,text,text,jsonb) to anon, authenticated;

